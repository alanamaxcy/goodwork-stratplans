/* File-backed portals.
   A portal served from a file in this repo rather than from the database:
   no account, no sign-in, and nothing an edit could be saved to.

     /demo    the anonymised sample portal — every section is illustrative.
              Always from its file, configured or not: it is public by design,
              and its banner says nothing is saved.
     /paact   the PAACT engagement's own content, from clients/paact/plan.js —
              but ONLY on a deploy with no Supabase project. Once a project is
              configured, /paact is the database portal its team signs in to
              and edits, and this file is what supabase/clients/paact.sql was
              generated from. The file copy is the read-only fallback that kept
              the address working before the database existed.

   A deploy with no Supabase project at all falls back to /demo for every other
   slug, so a fresh Netlify site shows the product instead of an error. */

import { engagementOfFile } from './engagement.js';

export const DEMO_SLUG = 'demo';
export const PAACT_SLUG = 'paact';

/* Every section of the product, in order. The same list both portals show. */
const ALL = ['scope', 'plan', 'findings', 'workplan', 'dashboard'];

/* ---------- the shared shape ----------
   One place where a data file becomes the portal record the app reads — the
   same fields a database row carries, so every section renders either. */

function filePortal({ id, slug, client, engagement, plan, findings, sections, sampleSections, sampleClient }) {
  return {
    id,
    slug,
    client_name: client.name,
    place: client.place,
    engagement_name: client.engagement,
    /* Null, not undefined, when nothing has been adopted: Plan.jsx prints
       "Adopted {date}." for any truthy value. */
    adopted: client.adopted || null,
    brand: {},
    labels: {},
    /* Which sections this portal SHOWS, in order. Defaults to all five; a
       portal passes fewer when fewer exist yet. Settings writes this field, so
       turning one on later is a click rather than a deploy. */
    sections: sections && sections.length ? sections : ALL,
    engagement,
    plan: {
      vision: plan.vision,
      framing: plan.framing,
      priorities: plan.priorities,
      track: plan.track,
    },
    findings,
    /* WHOSE the borrowed sections are. The sample is a whole other
       organisation's plan, and the masthead wears this name while you are
       reading them, so the identity on screen always matches the content
       under it rather than putting this client's name over someone else's
       priorities. Absent on a portal that borrows nothing. */
    sampleClient,
    /* Which of the five sections are illustrative rather than this client's
       own. The app marks these; a section not listed here is real content.
       Stated as data because the honest answer differs per portal, and a
       strategic plan showing priorities a client never agreed to is worse than
       no plan at all. */
    sampleSections,
  };
}

function fileTasks(rows) {
  /* Guarded: a portal whose workplan has not been built yet carries no tasks,
     and the portal has to render anyway. */
  return (rows || []).map((t, i) => ({
    id: t.id,
    parent: t.parent || null,
    init: t.obj,
    title: t.title,
    owner: t.owner || '',
    start: t.start || '',
    due: t.due || '',
    // The prototype carried a pseudo-status for a task that was merely late.
    // Late is derived from the due date; it is never stored.
    status: t.status === 'late' ? 'next' : t.status,
    note: '',
    position: i,
  }));
}

/* ---------- /demo ----------
   ANONYMISED content, generated by scripts/make-demo.mjs. This is served on a
   public URL with no sign-in, so it must never be a real client's discovery
   data — those are 933 candid congregation responses, and what identifies them
   is the organisation. A separate chunk too: findings alone is ~320 KB, and a
   signed-in client portal must never pay for data it will not use. */
export async function loadDemo() {
  const [{ PORTAL }, { FINDINGS }] = await Promise.all([
    import('../../clients/demo/plan.js'),
    import('../../clients/demo/findings.js'),
  ]);

  const portal = filePortal({
    id: 'demo',
    slug: DEMO_SLUG,
    client: PORTAL.client,
    engagement: { phases: PORTAL.phases, scope: PORTAL.scope, firm: PORTAL.firm },
    plan: PORTAL.plan,
    findings: FINDINGS,
    /* All five: there is no real client anywhere in this portal. */
    sampleSections: ALL,
  });

  /* The demo is dated content — phases, due dates and "past due" only read
     correctly relative to the engagement it describes, so the clock is pinned
     rather than letting the whole plan drift into the past. This pin is the
     ONLY one left: a real client's portal reads the real date (see loadPaact). */
  return { portal, tasks: fileTasks(PORTAL.tasks), now: PORTAL.today, role: DEMO_ROLE };
}

/* ---------- /paact, when there is no database ----------
   The engagement's own content, read-only. It carries no plan, findings or
   workplan, because PAACT has none yet — they are the OUTPUT of the engagement
   section 1 describes — and each is switched on from Settings on the day it
   has something in it. */
export async function loadPaact() {
  const { PORTAL: PAACT } = await import('../../clients/paact/plan.js');

  const portal = filePortal({
    id: 'paact',
    slug: PAACT_SLUG,
    client: PAACT.client,
    /* The same canonical document the database holds, so the fallback and
       the live portal render from one shape. */
    engagement: engagementOfFile(PAACT),
    plan: { vision: '', framing: '', priorities: [], track: null },
    findings: { themes: [], responses: [] },
    sections: ['scope'],
  });

  /* No pinned clock: `now: null`, and App.jsx reads the real local date.
     READ-ONLY, not owner: a file has nowhere to save to, and this address was
     printed as a QR code, so whoever scanned it would otherwise be handed edit
     controls whose every change vanished on reload. */
  return { portal, tasks: [], now: null, role: 'viewer' };
}

/* ---------- the registry ----------
   Which slugs the app can serve from files, and when. */
export const FILE_PORTALS = {
  [DEMO_SLUG]: loadDemo,
  [PAACT_SLUG]: loadPaact,
};

/* The file-backed portal that serves this slug, or null if the database does.

   /demo always comes from its file. Everything else comes from the database
   whenever one is configured — including /paact, whose file is only the
   fallback for a deploy with no project. Without a project (`unconfigured`),
   a slug with a file of its own gets it, and every other slug gets /demo,
   which is how a fresh Netlify site shows the product instead of an error. */
export function fileBackedSlug(slug, { unconfigured = false } = {}) {
  const s = String(slug || '').toLowerCase();
  if (s === DEMO_SLUG) return DEMO_SLUG;
  if (!unconfigured) return null;
  return Object.prototype.hasOwnProperty.call(FILE_PORTALS, s) ? s : DEMO_SLUG;
}

/* Load one. Resolves to { portal, tasks, now, role }, or to null when no file
   portal serves the slug. `now` pins the clock for a portal whose content is
   dated — only /demo does — and is null for a live engagement, which is how
   App.jsx knows to use the real local date. */
export function loadFilePortal(slug, opts) {
  const s = fileBackedSlug(slug, opts);
  return s ? FILE_PORTALS[s]() : Promise.resolve(null);
}

/* Owner, so a file portal shows the whole product — including the plan editor,
   which is what makes this a tool rather than a document. Nothing persists, so
   there is nothing to protect: the store's write calls no-op without a Supabase
   project, and every change dies with the tab. */
export const DEMO_ROLE = 'owner';
